function shuffleIdx(len, seedStr) {
  let s = 2166136261 >>> 0;
  for (let i = 0; i < seedStr.length; i++) { s ^= seedStr.charCodeAt(i); s = Math.imul(s, 16777619) >>> 0; }
  const a = Array.from({ length: len }, (_, i) => i);
  for (let i = len - 1; i > 0; i--) { s = (Math.imul(s, 1103515245) + 12345) >>> 0; const j = s % (i + 1); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}
function insPickN(arr, n) {
  if (!arr.length) return [];
  const idx = shuffleIdx(arr.length, insSeed());
  return idx.slice(0, Math.min(n, arr.length)).map(i => arr[i]);
}
